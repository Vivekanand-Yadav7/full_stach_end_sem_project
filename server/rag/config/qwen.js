const { llm } = require('./gemini');

const LOCAL_LLM_URL = process.env.LOCAL_LLM_URL || 'http://localhost:8000/v1/chat/completions';
const USE_LOCAL_LLM = process.env.USE_LOCAL_LLM !== 'false'; // default true
const TIMEOUT_MS = parseInt(process.env.LOCAL_LLM_TIMEOUT_MS || '90000', 10);

/**
 * Invokes the fine-tuned Qwen model (running via local FastAPI microservice)
 * with automatic fallback to Gemini if offline or unresponsive.
 *
 * @param {Array<{role: string, content: string}>} messages ChatML messages (system, user)
 * @param {string} rawPrompt Full text prompt string (for Gemini fallback)
 * @returns {Promise<{text: string, source: 'qwen'|'gemini'}>}
 */
async function generateShoppingRecommendation(messages, rawPrompt) {
  if (USE_LOCAL_LLM) {
    try {
      const controller = new AbortController();
      const timeoutId = setTimeout(() => controller.abort(), TIMEOUT_MS);

      const response = await fetch(LOCAL_LLM_URL, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          model: 'invenorder-qwen3.5-2b-lora',
          messages,
          temperature: 0.1,
          max_tokens: 40,
        }),
        signal: controller.signal,
      });

      clearTimeout(timeoutId);

      if (response.ok) {
        const data = await response.json();
        const content = data?.choices?.[0]?.message?.content;
        if (content && typeof content === 'string' && content.trim().length > 0) {
          console.log('🤖 Recommendation generated by fine-tuned Qwen 2B model');
          return { text: content.trim(), source: 'qwen' };
        }
      } else {
        console.warn(`Local model returned status ${response.status}: ${await response.text()}`);
      }
    } catch (err) {
      console.warn(
        `⚠️ Local Qwen service unavailable at ${LOCAL_LLM_URL} (${err.name || err.message}). Falling back to Gemini.`
      );
    }
  }

  // Fallback to Gemini
  console.log('✨ Generating recommendation via Google Gemini fallback');
  const geminiResponse = await llm.invoke(rawPrompt);
  return {
    text: geminiResponse.content ?? geminiResponse,
    source: 'gemini',
  };
}

module.exports = {
  generateShoppingRecommendation,
};
